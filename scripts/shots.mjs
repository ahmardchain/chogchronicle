import { chromium, devices } from 'playwright';
const U = process.env.URL || 'http://localhost:5173';
const b = await chromium.launch(); const errs = [];
const watch = p => { p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && !/favicon|ERR_|Failed to load resource/.test(m.text()) && errs.push(m.text())); };
const ctx = await b.newContext({ viewport: { width: 1400, height: 900 } }); const p = await ctx.newPage(); watch(p);
await p.goto(U + '/'); await p.waitForTimeout(2500); await p.screenshot({ path: 'shots/1-landing.png' });
await p.getByRole('button', { name: /Adopt a guest daemon/ }).click(); await p.waitForURL(/\/d\/\d+/); await p.waitForTimeout(2500);
const id = p.url().match(/\/d\/(\d+)/)[1];
await p.screenshot({ path: 'shots/2-daemon-adopted.png', fullPage: true });
await p.locator('.ocard', { hasText: 'Raid' }).first().click(); await p.waitForTimeout(500);
await p.screenshot({ path: 'shots/3-order-cards.png' });
await p.getByRole('button', { name: /^Seal / }).click(); await p.locator('.sealedbox').waitFor(); await p.waitForTimeout(1200);
await p.screenshot({ path: 'shots/4-order-sealed.png' });
await p.getByRole('button', { name: /Fast-forward the night/ }).click(); await p.locator('.modal').waitFor(); await p.waitForTimeout(2500);
const recap = await p.locator('.recaplist .diary').allTextContents();
await p.screenshot({ path: 'shots/5-recap.png' });
await p.getByRole('button', { name: /Back to the world/ }).click(); await p.waitForTimeout(1500);
const diary = await p.locator('.night').first().locator('.diary').count();
await p.goto(U + '/map'); await p.waitForTimeout(2500);
const box = await p.locator('.mapwrap canvas').first().boundingBox();
await p.mouse.click(box.x + box.width * 0.4, box.y + box.height * 0.45); await p.waitForTimeout(800);
await p.screenshot({ path: 'shots/6-map.png' });
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2); for (let i = 0; i < 5; i++) { await p.mouse.wheel(0, -200); await p.waitForTimeout(80); }
await p.waitForTimeout(800); await p.screenshot({ path: 'shots/7-map-zoomed.png' });
await p.goto(U + '/chronicle'); await p.waitForTimeout(2200); await p.screenshot({ path: 'shots/8-chronicle.png' });
const m = await b.newContext({ ...devices['iPhone 13'] }); const mp = await m.newPage(); watch(mp);
await mp.goto(U + '/'); await mp.waitForTimeout(2500); await mp.screenshot({ path: 'shots/9-mobile-landing.png', fullPage: true });
await mp.goto(U + '/d/' + id); await mp.waitForTimeout(2500); await mp.screenshot({ path: 'shots/10-mobile-daemon.png', fullPage: true });
console.log(JSON.stringify({ guest: id, recap, diaryEntriesToday: diary, errors: errs }, null, 1));
await b.close();
