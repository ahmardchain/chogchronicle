// Fetch Chog Genesis metadata (Monad tokenURI -> IPFS) for the daemon pool and cache 256px webp thumbnails.
import { createPublicClient, http, parseAbi } from 'viem';
import sharp from 'sharp';
import fs from 'fs';
const C = '0xc96d31F8626c6D03Fae5dCD3d61e3FB9F4a73763';
const c = createPublicClient({ transport: http('https://rpc.monad.xyz') });
const abi = parseAbi(['function tokenURI(uint256) view returns (string)']);
const G = 'https://gateway.pinata.cloud/ipfs/';
const base = [1, 7, 42, 69, 100, 143, 256, 420, 777, 1000, 1337, 1659];
const ids = [...new Set([...base, ...Array.from({ length: 84 }, (_, i) => 11 + i * 23)])].filter(i => i <= 1969).sort((a, b) => a - b);
const out = [];
async function one(id) {
  for (let a = 0; a < 3; a++) try {
    const uri = await c.readContract({ address: C, abi, functionName: 'tokenURI', args: [BigInt(id)] });
    const m = await (await fetch(uri.replace('ipfs://', G))).json();
    const file = `public/chogs/${id}.webp`;
    if (!fs.existsSync(file) || fs.statSync(file).size > 60000) {
      const img = Buffer.from(await (await fetch(m.image.replace('ipfs://', G))).arrayBuffer());
      await sharp(img).resize(256, 256).webp({ quality: 78 }).toFile(file + '.tmp'); fs.renameSync(file + '.tmp', file);
    }
    out.push({ tokenId: id, name: m.name, image: `/chogs/${id}.webp`, ipfsImage: m.image, attributes: m.attributes }); return;
  } catch (e) { if (a === 2) console.error('fail', id, e.message); }
}
for (let i = 0; i < ids.length; i += 8) { await Promise.all(ids.slice(i, i + 8).map(one)); console.log('done', Math.min(i + 8, ids.length), '/', ids.length); }
out.sort((a, b) => a.tokenId - b.tokenId);
fs.writeFileSync('shared/demoChogs.ts', '// Generated by scripts/fetch-chogs.mjs — cached Chog Genesis metadata for the daemon pool.\nimport type { Chog } from "./stats.js";\nexport const DEMO_CHOGS: Chog[] = ' + JSON.stringify(out) + ';\n');
console.log('pool', out.length);
